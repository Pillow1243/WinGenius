# ------------------------------------------------------------------- results
@dataclass
class StepResult:
    tool_id: str
    status: str = "pending"       # pending | running | done | failed | cancelled | skipped
    message: str = ""
    outputs: List[str] = field(default_factory=list)
    duration: float = 0.0


@dataclass
class WorkflowResult:
    workflow_id: str
    status: str = "done"
    steps: List[StepResult] = field(default_factory=list)
    message: str = ""

    @property
    def outputs(self) -> List[str]:
        out: List[str] = []
        for step in self.steps:
            for path in step.outputs:
                if path not in out:
                    out.append(path)
        return out

    @property
    def ok(self) -> bool:
        return self.status == "done"


def _initial_context(base_values: Optional[Dict[str, Any]]) -> Dict[str, Any]:
    base = dict(base_values or {})
    paths = list(base.get("__paths__") or [])
    if not paths and base.get("input"):
        paths = [str(base["input"])]
    context: Dict[str, Any] = {
        "prev": "", "prev_all": [], "prev_dir": "", "prev_name": "",
        "input": paths[0] if paths else "",
        "input_all": paths,
        "out_dir": str(base.get("out_dir") or data_dir()),
        "index": 0,
    }
    for key, value in base.items():
        if key not in ("__paths__", "out_dir"):
            context[key] = value
    return context


def _context_from_outputs(context: Dict[str, Any], outputs: List[str]) -> Dict[str, Any]:
    context = dict(context)
    first = outputs[0] if outputs else ""
    context["prev"] = first
    context["prev_all"] = list(outputs)
    context["prev_dir"] = str(Path(first).parent) if first else ""
    context["prev_name"] = Path(first).stem if first else ""
    return context


# --------------------------------------------------------------- sync runner
def run_sync(workflow: Workflow, lang: str = "fa", output_dir: str = "",
             base_values: Optional[Dict[str, Any]] = None,
             on_step: Optional[Callable[[int, StepResult], None]] = None,
             cancel_event: Optional[threading.Event] = None) -> WorkflowResult:
    """Run a workflow on the current thread (used by the CLI and by tests)."""
    result = WorkflowResult(workflow_id=workflow.id)
    context = _initial_context({**(base_values or {}), "out_dir": output_dir or ""})
    for index, step in enumerate(workflow.steps):
        spec = get_tool(step.tool_id)
        step_result = StepResult(tool_id=step.tool_id)
        result.steps.append(step_result)
        if spec is None:
            step_result.status = "failed"
            step_result.message = f"unknown tool: {step.tool_id}"
            result.status = "failed"
            result.message = step_result.message
            return result
        step_result.status = "running"
        if on_step:
            on_step(index, step_result)
        started = time.time()
        values = substitute({**step.values}, context)
        ctx = RunContext(lang=lang, output_dir=output_dir,
                         cancel_event=cancel_event or threading.Event())
        try:
            run_result = spec.run(ctx, values) if spec.run else None
            if not isinstance(run_result, RunResult):
                run_result = RunResult(message=str(run_result or ""))
        except Cancelled:
            step_result.status = "cancelled"
            result.status = "cancelled"
            result.message = "cancelled"
            return result
        except ToolError as exc:
            step_result.status = "failed"
            step_result.message = str(exc)
            result.status = "failed"
            result.message = f"{spec.name_for(lang)}: {exc}"
            return result
        except Exception as exc:  # pragma: no cover - defensive
            step_result.status = "failed"
            step_result.message = f"{type(exc).__name__}: {exc}"
            result.status = "failed"
            result.message = step_result.message
            return result
        step_result.status = "done"
        step_result.message = run_result.message
        step_result.outputs = list(run_result.outputs or [])
        step_result.duration = time.time() - started
        context = _context_from_outputs(context, step_result.outputs)
        if on_step:
            on_step(index, step_result)
    outputs = result.outputs
    result.message = (f"{len(workflow.steps)} گام انجام شد"
                      if lang != "en" else f"{len(workflow.steps)} steps finished")
    if outputs:
        result.message += f" · {len(outputs)} " + ("output(s)" if lang == "en" else "خروجی")
    return result


# ---------------------------------------------------------------- async runs
class WorkflowRunner(QObject):
    """Runs a workflow step by step in background threads (used by the UI)."""

    stepStarted = Signal(int, str, str)      # index, tool_id, title
    stepProgress = Signal(int, int, int, str)  # index, current, total, message
    stepFinished = Signal(int, str, str)     # index, status, message
    finished = Signal(object)                # WorkflowResult
    failed = Signal(str)

    def __init__(self, workflow: Workflow, lang: str = "fa", output_dir: str = "",
                 base_values: Optional[Dict[str, Any]] = None, parent=None) -> None:
        super().__init__(parent)
        self.workflow = workflow
        self.lang = lang
        self.output_dir = output_dir
        self.base_values = dict(base_values or {})
        self.context = _initial_context({**self.base_values, "out_dir": output_dir or ""})
        self.result = WorkflowResult(workflow_id=workflow.id)
        self._index = 0
        self._runner: Optional[ToolRunner] = None
        self._runners: List[ToolRunner] = []
        self._cancelled = False

    # ------------------------------------------------------------------ api
    def start(self) -> None:
        self._run_next()

    def cancel(self) -> None:
        self._cancelled = True
        if self._runner is not None:
            self._runner.cancel()

    @property
    def running(self) -> bool:
        return self._runner is not None

    def current_step(self) -> int:
        return self._index

    # -------------------------------------------------------------- internals
    def _run_next(self) -> None:
        if self._cancelled:
            self.result.status = "cancelled"
            self.finished.emit(self.result)
            return
        if self._index >= len(self.workflow.steps):
            self.result.status = "failed" if any(
                step.status == "failed" for step in self.result.steps) else "done"
            self.result.message = (
                f"{len(self.workflow.steps)} " + ("steps finished" if self.lang == "en" else "گام انجام شد"))
            self.finished.emit(self.result)
            return
        index = self._index
        step = self.workflow.steps[index]
        spec = get_tool(step.tool_id)
        step_result = StepResult(tool_id=step.tool_id, status="running")
        self.result.steps.append(step_result)
        if spec is None:
            step_result.status = "failed"
            step_result.message = f"unknown tool: {step.tool_id}"
            self.result.status = "failed"
            self.result.message = step_result.message
            self.failed.emit(step_result.message)
            self.finished.emit(self.result)
            return
        self.stepStarted.emit(index, step.tool_id, step.title(self.lang))
        values = substitute({**step.values}, self.context)
        runner = ToolRunner(spec, values, self.lang, self.output_dir, self)
        runner.progressed.connect(lambda current, total, message, idx=index:
                                  self.stepProgress.emit(idx, current, total, message))
        runner.succeeded.connect(lambda run_result, idx=index: self._on_step_done(idx, run_result))
        runner.failed.connect(lambda message, _trace, idx=index: self._on_step_failed(idx, message))
        runner.cancelled.connect(lambda idx=index: self._on_step_cancelled(idx))
        self._runner = runner
        self._runners.append(runner)
        runner.start()

    def _advance(self, index: int) -> None:
        self._runner = None
        self._index = index + 1
        self._run_next()

    def _on_step_done(self, index: int, run_result: RunResult) -> None:
        if index < len(self.result.steps):
            step_result = self.result.steps[index]
            step_result.status = "done"
            step_result.message = run_result.message
            step_result.outputs = list(run_result.outputs or [])
            self.context = _context_from_outputs(self.context, step_result.outputs)
        self.stepFinished.emit(index, "done", run_result.message)
        self._advance(index)

    def _on_step_failed(self, index: int, message: str) -> None:
        if index < len(self.result.steps):
            self.result.steps[index].status = "failed"
            self.result.steps[index].message = message
        self.result.status = "failed"
        self.result.message = message
        self.stepFinished.emit(index, "failed", message)
        self._runner = None
        self.failed.emit(message)
        self.finished.emit(self.result)

    def _on_step_cancelled(self, index: int) -> None:
        if index < len(self.result.steps):
            self.result.steps[index].status = "cancelled"
        self.result.status = "cancelled"
        self.result.message = "cancelled"
        self.stepFinished.emit(index, "cancelled", "cancelled")
        self._runner = None
        self.finished.emit(self.result)


# ------------------------------------------------------------------ builtins
def _wf(workflow_id: str, name: str, name_en: str, desc: str, desc_en: str,
        icon: str, steps: List[Step]) -> Dict[str, Any]:
    return {
        "id": workflow_id, "name": name, "name_en": name_en, "desc": desc, "desc_en": desc_en,
        "icon": icon, "source": "builtin", "created": 0.0,
        "steps": [step.as_dict() for step in steps],
    }


def _chain(tool_ids: List[str]) -> List[Step]:
    """Build steps, feeding every step the previous one's output."""
    steps: List[Step] = []
    for index, tool_id in enumerate(tool_ids):
        spec = get_tool(tool_id)
        if spec is None:
            log.warning("builtin workflow references unknown tool %s", tool_id)
            continue
        values = autofill(spec, []) if index == 0 else chain_values(spec)
        steps.append(Step(tool_id=tool_id, values=values))
    return steps


