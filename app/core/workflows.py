PLACEHOLDERS = ("{prev}", "{prev_all}", "{prev_dir}", "{prev_name}", "{input}", "{out_dir}")


# --------------------------------------------------------------------- model
@dataclass
class Step:
    tool_id: str
    values: Dict[str, Any] = field(default_factory=dict)
    note: str = ""

    def as_dict(self) -> Dict[str, Any]:
        return {"tool_id": self.tool_id, "values": sanitize_values(self.tool_id, self.values), "note": self.note}

    @staticmethod
    def from_dict(data: Dict[str, Any]) -> "Step":
        return Step(tool_id=str(data.get("tool_id", "")), values=dict(data.get("values") or {}),
                    note=str(data.get("note") or ""))

    def title(self, lang: str = "fa") -> str:
        spec = get_tool(self.tool_id)
        return spec.name_for(lang) if spec else self.tool_id

    def icon(self) -> str:
        spec = get_tool(self.tool_id)
        return spec.icon if spec else "gear"


@dataclass
class Workflow:
    id: str
    name: str
    steps: List[Step] = field(default_factory=list)
    name_en: str = ""
    desc: str = ""
    desc_en: str = ""
    icon: str = "layers"
    source: str = "user"          # user | builtin | plan
    created: float = field(default_factory=time.time)

    # ------------------------------------------------------------------ info
    def name_for(self, lang: str) -> str:
        return (self.name_en or self.name) if lang == "en" else (self.name or self.name_en)

    def desc_for(self, lang: str) -> str:
        return (self.desc_en or self.desc) if lang == "en" else (self.desc or self.desc_en)

    def step_titles(self, lang: str = "fa") -> List[str]:
        return [step.title(lang) for step in self.steps]

    # ------------------------------------------------------------------- io
    def as_dict(self) -> Dict[str, Any]:
        return {
            "id": self.id, "name": self.name, "name_en": self.name_en,
            "desc": self.desc, "desc_en": self.desc_en, "icon": self.icon,
            "source": self.source, "created": self.created,
            "steps": [step.as_dict() for step in self.steps],
        }

    @staticmethod
    def from_dict(data: Dict[str, Any]) -> "Workflow":
        return Workflow(
            id=str(data.get("id") or uuid.uuid4().hex[:10]),
            name=str(data.get("name") or "Workflow"),
            name_en=str(data.get("name_en") or ""),
            desc=str(data.get("desc") or ""),
            desc_en=str(data.get("desc_en") or ""),
            icon=str(data.get("icon") or "layers"),
            source=str(data.get("source") or "user"),
            created=float(data.get("created") or time.time()),
            steps=[Step.from_dict(item) for item in data.get("steps") or [] if item.get("tool_id")],
        )

    def clone(self, name: Optional[str] = None) -> "Workflow":
        copy_ = Workflow.from_dict(self.as_dict())
        copy_.id = uuid.uuid4().hex[:10]
        copy_.source = "user"
        copy_.created = time.time()
        if name:
            copy_.name = name
        return copy_


# ------------------------------------------------------------- field helpers
def input_field(spec: ToolSpec):
    """Return (key, takes_list) of the tool's main input field ('' if none)."""
    for wanted_list in (True, False):
        for f in spec.fields:
            if wanted_list and f.kind == K_FILES:
                return f.key, True
            if not wanted_list and f.kind in (K_FILE, K_DIR):
                return f.key, False
    return "", False


def autofill(spec: ToolSpec, paths: List[str], output_dir: str = "") -> Dict[str, Any]:
    """Default values for `spec`, with `paths` written into its input field."""
    values = spec.defaults()
    key, takes_list = input_field(spec)
    if key and paths:
        values[key] = list(paths) if takes_list else paths[0]
    if output_dir:
        for f in spec.fields:
            if f.kind in (K_DIR, K_FILE) and f.key != key:
                values[f.key] = output_dir
    return values


def chain_values(spec: ToolSpec, placeholder: str = "{prev}") -> Dict[str, Any]:
    """Values that feed the previous step's output into `spec`."""
    values = spec.defaults()
    key, takes_list = input_field(spec)
    if key:
        values[key] = ["{prev_all}"] if takes_list else placeholder
    return values


def missing_required(workflow: Workflow) -> List[str]:
    """Human readable list of required fields that still have no value."""
    problems: List[str] = []
    for index, step in enumerate(workflow.steps, start=1):
        spec = get_tool(step.tool_id)
        if spec is None:
            problems.append(f"#{index}: unknown tool {step.tool_id}")
            continue
        for f in spec.fields:
            if not f.required:
                continue
            value = step.values.get(f.key)
            if value in (None, "", []):
                problems.append(f"#{index} {spec.name}: {f.label or f.key}")
    return problems


def substitute(values: Dict[str, Any], context: Dict[str, Any]) -> Dict[str, Any]:
    """Replace {prev} style tokens inside string / list values."""
    out: Dict[str, Any] = {}
    for key, value in (values or {}).items():
        out[key] = _sub_value(value, context)
    return out


def _sub_value(value: Any, context: Dict[str, Any]) -> Any:
    if isinstance(value, str):
        if value in ("{prev_all}", "{input_all}"):
            target = "{prev_all}" if value == "{prev_all}" else "{input_all}"
            items = context.get("prev_all" if target == "{prev_all}" else "input_all") or []
            return [str(item) for item in items]
        text = value
        for token in PLACEHOLDERS:
            if token in text:
                replacement = context.get(token.strip("{}"), "")
                if value.strip() == token:
                    return str(replacement or "")
                text = text.replace(token, str(replacement or ""))
        return text
    if isinstance(value, list):
        out: List[Any] = []
        for item in value:
            subbed = _sub_value(item, context)
            if isinstance(subbed, list):
                out.extend(subbed)
            else:
                out.append(subbed)
        return out
    return value


# --------------------------------------------------------------- persistence
class WorkflowStore:
    """Built-in recipes + the user's own workflows (JSON in the data folder)."""

    def __init__(self) -> None:
        self._path = data_dir() / "workflows.json"
        self._user: List[Workflow] = []
        self._loaded = False

    # ------------------------------------------------------------------- io
    def _load(self) -> None:
        if self._loaded:
            return
        self._loaded = True
        try:
            if self._path.exists():
                original = json.loads(self._path.read_text(encoding="utf-8"))
                raw = sanitize_document(original)
                if raw != original:
                    atomic_json_write(self._path, raw)
                self._user = [Workflow.from_dict(item) for item in raw if item.get("steps")]
        except Exception as exc:  # pragma: no cover - corrupt file must not crash
            log.warning("cannot read workflows: %s", exc)
            self._user = []

    def _save(self) -> None:
        try:
            atomic_json_write(self._path, [wf.as_dict() for wf in self._user])
        except Exception as exc:  # pragma: no cover
            log.warning("cannot write workflows: %s", exc)

    # ------------------------------------------------------------------ api
    @property
    def path(self) -> Path:
        return self._path

    def builtins(self) -> List[Workflow]:
        return [Workflow.from_dict(item) for item in BUILTIN_WORKFLOWS]

    def user_items(self) -> List[Workflow]:
        self._load()
        return list(self._user)

    def all(self) -> List[Workflow]:
        return self.user_items() + self.builtins()

    def get(self, workflow_id: str) -> Optional[Workflow]:
        for wf in self.all():
            if wf.id == workflow_id:
                return wf
        return None

    def save(self, workflow: Workflow) -> Workflow:
        self._load()
        for index, existing in enumerate(self._user):
            if existing.id == workflow.id:
                self._user[index] = workflow
                break
        else:
            self._user.insert(0, workflow)
        self._save()
        return workflow

    def delete(self, workflow_id: str) -> bool:
        self._load()
        before = len(self._user)
        self._user = [wf for wf in self._user if wf.id != workflow_id]
        if len(self._user) != before:
            self._save()
            return True
        return False

    def new(self, name: str = "", steps: Optional[List[Step]] = None) -> Workflow:
        return Workflow(id=uuid.uuid4().hex[:10], name=name or "گردش‌کار تازه",
                        name_en="New workflow", steps=list(steps or []), source="user")


