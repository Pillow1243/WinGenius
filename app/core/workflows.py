"""Workflow engine: chain several tools into one run.

A workflow is an ordered list of steps; every step is a normal WinGenius tool
with a value dict.  Values may contain placeholders that are filled from the
previous step, which is what turns a bag of tools into real automation:

    {prev}       the first output of the previous step
    {prev_all}   every output of the previous step (used for list fields)
    {prev_dir}   folder of {prev}
    {prev_name}  file name of {prev} without extension
    {input}      the first file the workflow was started with
    {out_dir}    the configured output folder

Workflows can be built by hand (UI), generated by the assistant (planner) or
loaded from the shipped library of recipes.
"""
