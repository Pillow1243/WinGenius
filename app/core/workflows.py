PLACEHOLDERS = ("{prev}", "{prev_all}", "{prev_dir}", "{prev_name}", "{input}", "{out_dir}")


# --------------------------------------------------------------------- model
ON_ERROR_MODES = ("stop", "continue")

# Extra placeholders that only exist inside a `foreach` step.
ITEM_PLACEHOLDERS = ("{item}", "{item_name}", "{item_dir}", "{item_ext}", "{item_index}", "{item_count}")

ALL_PLACEHOLDERS = PLACEHOLDERS + ITEM_PLACEHOLDERS


@dataclass
class Step:
    """One tool call inside a flow.

    v6 adds four optional controls that turn a linear chain into a real flow:

    * ``when``     — a condition; the step is skipped when it is false.
    * ``foreach``  — a glob (or ``{prev_all}`` / ``{input_all}``) expanded into
      one run per item, with ``{item}``, ``{item_name}``, ``{item_dir}``,
      ``{item_ext}``, ``{item_index}`` and ``{item_count}`` available.
    * ``retries``  — retry a failing step N extra times (for flaky I/O).
    * ``on_error`` — ``stop`` (default) or ``continue`` to keep the flow going.
    """

    tool_id: str
    values: Dict[str, Any] = field(default_factory=dict)
    note: str = ""
    when: str = ""
    foreach: str = ""
    retries: int = 0
    on_error: str = "stop"
    label: str = ""

    def as_dict(self) -> Dict[str, Any]:
        data: Dict[str, Any] = {
            "tool_id": self.tool_id,
            "values": sanitize_values(self.tool_id, self.values),
            "note": self.note,
            "label": self.label,
        }
        if self.when:
            data["when"] = self.when
        if self.foreach:
            data["foreach"] = self.foreach
        if self.retries:
            data["retries"] = int(self.retries)
        if self.on_error and self.on_error != "stop":
            data["on_error"] = self.on_error
        return data

    @staticmethod
    def from_dict(data: Dict[str, Any]) -> "Step":
        mode = str(data.get("on_error") or "stop")
        try:
            retries = int(data.get("retries") or 0)
        except (TypeError, ValueError):
            retries = 0
        return Step(tool_id=str(data.get("tool_id", "")), values=dict(data.get("values") or {}),
                    note=str(data.get("note") or ""), when=str(data.get("when") or ""),
                    foreach=str(data.get("foreach") or ""),
                    retries=max(0, min(5, retries)),
                    on_error=mode if mode in ON_ERROR_MODES else "stop",
                    label=str(data.get("label") or ""))

    def title(self, lang: str = "fa") -> str:
        spec = get_tool(self.tool_id)
        base = spec.name_for(lang) if spec else self.tool_id
        return f"{self.label} · {base}" if self.label else base

    def icon(self) -> str:
        spec = get_tool(self.tool_id)
        return spec.icon if spec else "gear"

    # ------------------------------------------------------------------ flow
    @property
    def advanced(self) -> bool:
        """True when the step uses any v6 control (used as a UI badge)."""
        return bool(self.when or self.foreach or self.retries
                    or (self.on_error and self.on_error != "stop"))

    def summary(self, lang: str = "fa") -> str:
        """One-line description of the step's condition/loop/error policy."""
        parts: List[str] = []
        if self.when:
            parts.append(("اگر " if lang != "en" else "if ") + self.when)
        if self.foreach:
            parts.append(("برای هر " if lang != "en" else "for each ") + self.foreach)
        if self.retries:
            parts.append((f"{self.retries} تلاش دوباره" if lang != "en"
                          else f"{self.retries} retr" + ("y" if self.retries == 1 else "ies")))
        if self.on_error == "continue":
            parts.append("خطا را نادیده بگیر" if lang != "en" else "continue on error")
        return " · ".join(parts)


@dataclass
class Workflow:
    id: str
    name: str
    steps: List[Step] = field(default_factory=list)
    name_en: str = ""
    desc: str = ""
    desc_en: str = ""
    icon: str = "layers"
    source: str = "user"          # user | builtin | plan
    created: float = field(default_factory=time.time)

    # ------------------------------------------------------------------ info
    def name_for(self, lang: str) -> str:
        return (self.name_en or self.name) if lang == "en" else (self.name or self.name_en)

    def desc_for(self, lang: str) -> str:
        return (self.desc_en or self.desc) if lang == "en" else (self.desc or self.desc_en)

    def step_titles(self, lang: str = "fa") -> List[str]:
        return [step.title(lang) for step in self.steps]

    # ------------------------------------------------------------------- io
    def as_dict(self) -> Dict[str, Any]:
        return {
            "id": self.id, "name": self.name, "name_en": self.name_en,
            "desc": self.desc, "desc_en": self.desc_en, "icon": self.icon,
            "source": self.source, "created": self.created,
            "steps": [step.as_dict() for step in self.steps],
        }

    @staticmethod
    def from_dict(data: Dict[str, Any]) -> "Workflow":
        return Workflow(
            id=str(data.get("id") or uuid.uuid4().hex[:10]),
            name=str(data.get("name") or "Workflow"),
            name_en=str(data.get("name_en") or ""),
            desc=str(data.get("desc") or ""),
            desc_en=str(data.get("desc_en") or ""),
            icon=str(data.get("icon") or "layers"),
            source=str(data.get("source") or "user"),
            created=float(data.get("created") or time.time()),
            steps=[Step.from_dict(item) for item in data.get("steps") or [] if item.get("tool_id")],
        )

    def clone(self, name: Optional[str] = None) -> "Workflow":
        copy_ = Workflow.from_dict(self.as_dict())
        copy_.id = uuid.uuid4().hex[:10]
        copy_.source = "user"
        copy_.created = time.time()
        if name:
            copy_.name = name
        return copy_


# ------------------------------------------------------------- field helpers
def input_field(spec: ToolSpec):
    """Return (key, takes_list) of the tool's main input field ('' if none)."""
    for wanted_list in (True, False):
        for f in spec.fields:
            if wanted_list and f.kind == K_FILES:
                return f.key, True
            if not wanted_list and f.kind in (K_FILE, K_DIR):
                return f.key, False
    return "", False


def autofill(spec: ToolSpec, paths: List[str], output_dir: str = "") -> Dict[str, Any]:
    """Default values for `spec`, with `paths` written into its input field."""
    values = spec.defaults()
    key, takes_list = input_field(spec)
    if key and paths:
        values[key] = list(paths) if takes_list else paths[0]
    if output_dir:
        for f in spec.fields:
            if f.kind in (K_DIR, K_FILE) and f.key != key:
                values[f.key] = output_dir
    return values


def chain_values(spec: ToolSpec, placeholder: str = "{prev}") -> Dict[str, Any]:
    """Values that feed the previous step's output into `spec`."""
    values = spec.defaults()
    key, takes_list = input_field(spec)
    if key:
        values[key] = ["{prev_all}"] if takes_list else placeholder
    return values


def missing_required(workflow: Workflow) -> List[str]:
    """Human readable list of required fields that still have no value."""
    problems: List[str] = []
    for index, step in enumerate(workflow.steps, start=1):
        spec = get_tool(step.tool_id)
        if spec is None:
            problems.append(f"#{index}: unknown tool {step.tool_id}")
            continue
        for f in spec.fields:
            if not f.required:
                continue
            value = step.values.get(f.key)
            if value in (None, "", []):
                problems.append(f"#{index} {spec.name}: {f.label or f.key}")
    return problems


def substitute(values: Dict[str, Any], context: Dict[str, Any]) -> Dict[str, Any]:
    """Replace {prev} style tokens inside string / list values."""
    out: Dict[str, Any] = {}
    for key, value in (values or {}).items():
        out[key] = _sub_value(value, context)
    return out


def _sub_value(value: Any, context: Dict[str, Any]) -> Any:
    if isinstance(value, str):
        if value in ("{prev_all}", "{input_all}"):
            target = "{prev_all}" if value == "{prev_all}" else "{input_all}"
            items = context.get("prev_all" if target == "{prev_all}" else "input_all") or []
            return [str(item) for item in items]
        text = value
        for token in ALL_PLACEHOLDERS:
            if token in text:
                replacement = context.get(token.strip("{}"), "")
                if value.strip() == token:
                    return str(replacement or "")
                text = text.replace(token, str(replacement or ""))
        return text
    if isinstance(value, list):
        out: List[Any] = []
        for item in value:
            subbed = _sub_value(item, context)
            if isinstance(subbed, list):
                out.extend(subbed)
            else:
                out.append(subbed)
        return out
    return value


# ------------------------------------------------------------ v6 flow pieces
_FALSE_WORDS = {"", "0", "0.0", "false", "no", "off", "none", "null", "nil", "{}", "[]"}

# Longest first so `not exists` wins over `exists`.
_CONDITION_OPS = (
    "not exists", "not empty", "exists", "is empty", "startswith", "ends with",
    "starts with", "endswith", "contains", ">=", "<=", "!=", "==", ">", "<", "=",
)

_ITEM_GLOB_CHARS = ("*", "?", "[")


def truthy(value: Any) -> bool:
    """Lenient truthiness used by conditions (`0`, `false`, `` are false)."""
    if isinstance(value, bool):
        return value
    if value is None:
        return False
    if isinstance(value, (int, float)):
        return value != 0
    if isinstance(value, (list, tuple, set, dict)):
        return len(value) > 0
    return str(value).strip().lower() not in _FALSE_WORDS


def _as_number(text: str) -> Optional[float]:
    try:
        return float(str(text).strip().replace(",", ""))
    except (TypeError, ValueError):
        return None


def _compare(left: str, op: str, right: str) -> bool:
    low_left, low_right = str(left).strip().lower(), str(right).strip().lower()
    if op in ("==", "="):
        left_num, right_num = _as_number(left), _as_number(right)
        if left_num is not None and right_num is not None:
            return left_num == right_num
        return low_left == low_right
    if op == "!=":
        return not _compare(left, "==", right)
    if op in (">", "<", ">=", "<="):
        left_num, right_num = _as_number(left), _as_number(right)
        if left_num is None or right_num is None:
            left_num, right_num = float(len(low_left)), float(len(low_right))
        return {">": left_num > right_num, "<": left_num < right_num,
                ">=": left_num >= right_num, "<=": left_num <= right_num}[op]
    if op == "contains":
        return low_right in low_left
    if op in ("startswith", "starts with"):
        return low_left.startswith(low_right)
    if op in ("endswith", "ends with"):
        return low_left.endswith(low_right)
    if op in ("exists", "not exists"):
        text = str(left).strip()
        if not text:
            return op == "not exists"
        looks_like_path = os.sep in text or "/" in text or bool(Path(text).suffix)
        present = os.path.exists(text) if looks_like_path else True
        return (not present) if op == "not exists" else present
    if op == "is empty":
        return not truthy(left)
    if op == "not empty":
        return truthy(left)
    return truthy(left)


def _condition_clause(clause: str, context: Dict[str, Any]) -> bool:
    text = clause.strip()
    if not text:
        return True
    negate = False
    while text.lower().startswith("not "):
        negate = not negate
        text = text[4:].strip()
    for op in _CONDITION_OPS:
        needle = f" {op} "
        index = text.lower().find(needle)
        if index == -1:
            if text.lower().endswith(f" {op}"):
                left = resolve_text(text[: -len(op) - 1], context)
                verdict = _compare(left, op, "")
                return (not verdict) if negate else verdict
            continue
        left = resolve_text(text[:index], context)
        right = resolve_text(text[index + len(needle):], context)
        verdict = _compare(left, op, right)
        return (not verdict) if negate else verdict
    return (not truthy(resolve_text(text, context))) if negate else truthy(resolve_text(text, context))


def evaluate_condition(expression: str, context: Dict[str, Any]) -> bool:
    """Evaluate a flow condition without `eval` (safe on user-supplied text).

    Grammar: ``clause (and|or clause)*`` where ``and``/``or`` are left-associative
    and support ``&&``/``||``.  A clause is ``{placeholder} op value`` with one of
    ``== != > < >= <= contains startswith endswith exists not exists
    is empty not empty``; a bare placeholder is true when it is non-empty.
    """
    text = (expression or "").strip()
    if not text:
        return True
    parts = re.split(r"\s+(and|or|&&|\|\|)\s+", text, flags=re.I)
    if not parts:
        return True
    verdict = _condition_clause(parts[0], context)
    # Left-associative on purpose: `a or b and c` is `(a or b) and c`.
    # Documented in ARCHITECTURE.md so nobody has to guess.
    for index in range(1, len(parts) - 1, 2):
        operator = parts[index].strip().lower()
        right = _condition_clause(parts[index + 1], context)
        verdict = (verdict or right) if operator in ("or", "||") else (verdict and right)
    return bool(verdict)


def resolve_text(template: Any, context: Dict[str, Any]) -> Any:
    """Public alias for the placeholder substitution used by flow conditions."""
    return _sub_value(template, context)


def expand_foreach(pattern: Any, context: Dict[str, Any]) -> List[str]:
    """Expand a `foreach` pattern into concrete paths (sorted naturally).

    Accepts a glob (``{input_dir}/*.pdf``), a list placeholder
    (``{prev_all}``) or a single existing path.  Brace globs such as
    ``*.{jpg,png}`` are supported because Windows users write them.
    """
    resolved = resolve_text(pattern, context)
    if isinstance(resolved, (list, tuple)):
        return [str(item) for item in resolved if str(item).strip()]
    text = str(resolved or "").strip()
    if not text:
        return []
    text = os.path.expandvars(os.path.expanduser(text))
    if _glob.has_magic(text) or "{" in text:
        patterns = [text]
        if "{" in text and "}" in text:
            head, _, rest = text.partition("{")
            options, _, tail = rest.partition("}")
            patterns = [f"{head}{option.strip()}{tail}" for option in options.split(",")]
        found: List[str] = []
        for item in patterns:
            found.extend(_glob.glob(item, recursive=True))
        unique: List[str] = []
        for path in sorted(found, key=lambda p: p.lower()):
            if path not in unique:
                unique.append(path)
        return unique
    return [text] if os.path.exists(text) else []


def item_context(base: Dict[str, Any], item: str, index: int, count: int) -> Dict[str, Any]:
    context = dict(base)
    path = Path(str(item))
    context.update({
        "item": str(item),
        "item_name": path.stem,
        "item_dir": str(path.parent),
        "item_ext": path.suffix.lower(),
        "item_index": index + 1,
        "item_count": count,
    })
    return context


def step_value_sets(step: Step, context: Dict[str, Any]) -> List[Dict[str, Any]]:
    """The one (or N) value dicts a step should run with, placeholders resolved."""
    if not step.foreach:
        return [substitute({**step.values}, context)]
    items = expand_foreach(step.foreach, context)
    total = len(items)
    sets: List[Dict[str, Any]] = []
    for index, item in enumerate(items):
        sets.append(substitute({**step.values}, item_context(context, item, index, total)))
    return sets


# --------------------------------------------------------------- persistence
class WorkflowStore:
    """Built-in recipes + the user's own workflows (JSON in the data folder)."""

    def __init__(self) -> None:
        self._path = data_dir() / "workflows.json"
        self._user: List[Workflow] = []
        self._loaded = False

    # ------------------------------------------------------------------- io
    def _load(self) -> None:
        if self._loaded:
            return
        self._loaded = True
        try:
            if self._path.exists():
                original = json.loads(self._path.read_text(encoding="utf-8"))
                raw = sanitize_document(original)
                if raw != original:
                    atomic_json_write(self._path, raw)
                self._user = [Workflow.from_dict(item) for item in raw if item.get("steps")]
        except Exception as exc:  # pragma: no cover - corrupt file must not crash
            log.warning("cannot read workflows: %s", exc)
            self._user = []

    def _save(self) -> None:
        try:
            atomic_json_write(self._path, [wf.as_dict() for wf in self._user])
        except Exception as exc:  # pragma: no cover
            log.warning("cannot write workflows: %s", exc)

    # ------------------------------------------------------------------ api
    @property
    def path(self) -> Path:
        return self._path

    def builtins(self) -> List[Workflow]:
        return [Workflow.from_dict(item) for item in BUILTIN_WORKFLOWS]

    def user_items(self) -> List[Workflow]:
        self._load()
        return list(self._user)

    def all(self) -> List[Workflow]:
        return self.user_items() + self.builtins()

    def get(self, workflow_id: str) -> Optional[Workflow]:
        for wf in self.all():
            if wf.id == workflow_id:
                return wf
        return None

    def save(self, workflow: Workflow) -> Workflow:
        self._load()
        for index, existing in enumerate(self._user):
            if existing.id == workflow.id:
                self._user[index] = workflow
                break
        else:
            self._user.insert(0, workflow)
        self._save()
        return workflow

    def delete(self, workflow_id: str) -> bool:
        self._load()
        before = len(self._user)
        self._user = [wf for wf in self._user if wf.id != workflow_id]
        if len(self._user) != before:
            self._save()
            return True
        return False

    def new(self, name: str = "", steps: Optional[List[Step]] = None) -> Workflow:
        return Workflow(id=uuid.uuid4().hex[:10], name=name or "گردش‌کار تازه",
                        name_en="New workflow", steps=list(steps or []), source="user")


